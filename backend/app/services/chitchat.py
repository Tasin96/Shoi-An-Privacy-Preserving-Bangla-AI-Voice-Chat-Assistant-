def get_chitchat_response(message: str) -> Optional[Tuple[str, float]]:
    """
    Checks if user input is an everyday Bangla conversational query (greetings, chitchat, identity).
    If it's a medical query, returns None so RAG / Clinical retriever handles it.
    Returns (response_text, confidence) if matched, or None.
    """
    if not message:
        return None

    # If message contains explicit medical keywords, defer to clinical/RAG engine
    if is_medical_query(message):
        return None

    norm_msg = normalize_bangla_text(message.strip().lower())
    
    # Strip common punctuation for regex matching
    clean_msg = re.sub(r"[?!.,।\-_~]", " ", norm_msg).strip()

    for pattern, responses in CONVERSATIONAL_INTENTS:
        if re.search(pattern, clean_msg, re.IGNORECASE):
            reply = random.choice(responses)
            return reply, 0.95

    return None

def get_open_ended_companion_response(message: str) -> str:
    """
    Provides a warm, supportive sisterly reply for general conversational remarks
    that do not contain specific clinical or medical keywords.
    """
    return random.choice(GENERAL_CHAT_RESPONSES)
