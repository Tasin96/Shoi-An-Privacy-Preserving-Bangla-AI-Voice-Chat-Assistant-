def get_chitchat_response(message: str) -> Optional[Tuple[str, float]]:
    """
    Checks if user input is an everyday Bangla conversational query (greetings, chitchat, identity).
    Returns (response_text, confidence) if matched, or None.
    """
    if not message:
        return None

    norm_msg = normalize_bangla_text(message.strip().lower())
    
    # Strip common punctuation
    clean_msg = re.sub(r"[?!.,।\-_~]", " ", norm_msg).strip()

    for pattern, responses in CONVERSATIONAL_INTENTS:
        if re.search(pattern, clean_msg, re.IGNORECASE):
            # Select random reply variation for natural conversation
            reply = random.choice(responses)
            return reply, 0.95

    return None
