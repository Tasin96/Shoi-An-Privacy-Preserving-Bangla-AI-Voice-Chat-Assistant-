def is_medical_query(text: str) -> bool:
    """Checks if text contains clinical or reproductive health keywords."""
    norm = normalize_bangla_text(text.lower())
    words = set(re.findall(r"[\u0980-\u09ffA-Za-z]+", norm))
    return bool(words.intersection(CLINICAL_KEYWORDS))

def normalize_conversational_text(text: str) -> str:
    """
    Normalizes spoken Bangla, phonetic repetitions, colloquial rural dialects, and common Banglish:
    - Collapses repeated chars (হুমমম -> হুম, হুউউ -> হু, হ্যালোওও -> হ্যালো)
    - Maps rural/colloquial speech to standard forms (করতাছো -> করছো, কেমুন -> কেমন, মনডা -> মন)
    - Translates common Banglish words to Bangla equivalents
    """
    if not text:
        return ""
    
    # 1. Base Bangla normalization
    text = normalize_bangla_text(text.strip().lower())

    # 2. Collapse character elongation (e.g. হুমমম -> হুম, হুউউ -> হু, আরেএএ -> আরে)
    text = re.sub(r'হুম+', 'হুম', text)
    text = re.sub(r'হু+', 'হু', text)
    text = re.sub(r'আচ্ছা+', 'আচ্ছা', text)
    text = re.sub(r'([ক-হয়ড়ঢ়য়])\1{2,}', r'\1', text)

    # 3. Banglish to Bengali transliteration mapping
    banglish_map = [
        (r'\bkemon\s*acho\b|\bkemon\s*asen\b', 'কেমন আছো'),
        (r'\bki\s*khobor\b|\bkee\s*khobor\b', 'কি খবর'),
        (r'\bki\s*korcho\b|\bki\s*korteso\b', 'কী করছো'),
        (r'\bvalo\s*achi\b|\bbalo\s*asi\b', 'ভালো আছি'),
        (r'\btumi\s*ke\b', 'তুমি কে'),
        (r'\bshoi\b', 'সই'),
        (r'\bmon\s*kharap\b', 'মন খারাপ'),
        (r'\bhello\b|\bhi\b|\bhey\b', 'হ্যালো'),
        (r'\bthanks\b|\bthank\s*you\b', 'ধন্যবাদ'),
        (r'\bbored\b|\bboring\b', 'বোরিং'),
        (r'\btired\b', 'ক্লান্ত'),
        (r'\btension\b|\bstress\b', 'টেনশন'),
        (r'\bheadache\b', 'মাথাব্যথা'),
        (r'\bpet\s*betha\b|\bpet\s*byatha\b', 'পেট ব্যথা'),
        (r'\blove\s*you\b', 'তোমাকে ভালোবাসি'),
        (r'\bbye\b|\bbyee\b|\btata\b', 'বিদায়'),
        (r'\bok\b|\bokay\b', 'ঠিক আছে'),
        (r'\blagche\b|\blagtese\b|\blagteche\b', 'লাগছে'),
        (r'\bkoro\b|\bkorun\b', 'করো'),
        (r'\bbolo\b|\bbolun\b', 'বলো'),
        (r'\bshuno\b|\bshunun\b', 'শোনো'),
        (r'\bhelp\b', 'সাহায্য'),
        (r'\bplease\b', 'দয়া করে'),
    ]
    for pattern, repl in banglish_map:
        text = re.sub(pattern, repl, text, flags=re.IGNORECASE)

    # 4. Regional & Colloquial Rural Bangla Dialect mapping
    dialect_map = [
        (r'কী\s*করতাছো|কি\s*করতেছো|কী\s*করতাছেন', 'কী করছো'),
        (r'কেমুন|কেমনে|ক্যামনে', 'কেমন'),
        (r'চলতাছে|চলতাসে', 'চলছে'),
        (r'কই\s*আছো|কই\s*তুমি|কই\s*থাকো', 'কোথায় আছো'),
        (r'কও\s*দেহি|কও', 'বলো দেখি'),
        (r'আইচ্ছা\s*হুনো|হুনো|হুনছেন', 'শোনো'),
        (r'আইচ্ছা|আইচ্চা', 'আচ্ছা'),
        (r'মনডা', 'মন'),
        (r'শরীলডা|শরীল', 'শরীর'),
        (r'মাথাডা', 'মাথা'),
        (r'পেটডা', 'পেট'),
        (r'ভালা\s*আছো\s*নি|ভালা\s*নি|ভালা\s*আছো|ভালা', 'ভালো আছো'),
        (r'খাইছো\s*নি|খাইছেন\s*নি', 'খেয়েছো কি'),
        (r'ঘুমাইছো\s*নি', 'ঘুমিয়েছো কি'),
        (r'কিয়ের\s*লাইগা|কিসের\s*লাইগা', 'কেন'),
        (r'ক্যান\s*এমন\s*অয়|ক্যান', 'কেন'),
        (r'হ', 'হ্যাঁ'),
    ]
    for pattern, repl in dialect_map:
        text = re.sub(rf"(?<![\u0980-\u09ffA-Za-z])(?:{pattern})(?![\u0980-\u09ffA-Za-z])", repl, text)

    return text

